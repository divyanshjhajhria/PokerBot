def preflop_equity(hole, n_opp):
    """Equity vs n_opp random hands, O(1) from the baked table."""
    c1, c2 = hole
    n = max(1, min(n_opp, max(PREFLOP_EQ)))
    return PREFLOP_EQ[n][hand_class(c1, c2)]


def top_range(frac):
    """169 weights for the top `frac` of all 1326 combos (by HU equity)."""
    w = [0.0] * 169
    want = max(0.0, min(1.0, frac)) * 1326.0
    got = 0.0
    for i in HAND_ORDER:
        if got >= want:
            break
        n = CLASS_NCOMBOS[i]
        take = min(1.0, (want - got) / n)
        w[i] = take
        got += take * n
    return w


def preflop_equity_vs_range(hole, weights):
    """HU all-in equity of `hole` vs a 169-weight range, with card removal."""
    c1, c2 = hole
    i = hand_class(c1, c2)
    base = i * 169
    num = den = 0.0
    E, W = HU_E, HU_W
    for j in range(169):
        wj = weights[j]
        if wj:
            ww = wj * W[base + j]
            num += ww * E[base + j]
            den += ww
    return num / den if den else 0.5


def range_combos(weights, dead=(), min_weight=0.5):
    """Expand a 169-weight range into specific combos avoiding dead cards."""
    dead = set(dead)
    out = []
    for j in range(169):
        if weights[j] >= min_weight:
            for a, b in CLASS_COMBOS[j]:
                if a not in dead and b not in dead:
                    out.append((a, b))
    return out


def equity_mc(hero, board, n_opp=1, ranges=None, iters=2000, deadline=None, rng=None):
    """Monte Carlo equity (ties split) of int cards `hero` on int `board`.

    ranges: None (all random) or a list of length n_opp with, per opponent,
            None (random) or a list of (c1, c2) combos.
    deadline: absolute perf_counter() time after which sampling stops.
    Returns (equity, samples_used).
    """
    rnd = (rng or random).random
    hero = list(hero)
    board = list(board)
    if ranges is not None:
        dead = set(hero) | set(board)
        clean = []
        for cl in ranges:
            if cl:
                cl = [x for x in cl if x[0] not in dead and x[1] not in dead]
            clean.append(cl or None)
        if any(cl is not None for cl in clean):
            return _mc_ranged(hero, board, clean, iters, deadline, rnd)
    return _mc_random(hero, board, n_opp, iters, deadline, rnd)


def _mc_random(hero, board, n_opp, iters, deadline, rnd):
    CV, NF = _CV, _NF
    dead = set(hero) | set(board)
    deck = [c for c in range(52) if c not in dead]
    L = len(deck)
    nb = 5 - len(board)
    need = nb + 2 * n_opp
    bt0 = 0
    for c in board:
        bt0 += CV[c]
    ht = CV[hero[0]] + CV[hero[1]]
    total = 0.0
    n = 0
    for it in range(iters):
        if deadline is not None and it and not (it & 63) and perf_counter() > deadline:
            break
        for i in range(need):
            j = i + int(rnd() * (L - i))
            deck[i], deck[j] = deck[j], deck[i]
        bt = bt0
        for i in range(nb):
            bt += CV[deck[i]]
        t = bt + ht
        if (t + 0x3333) & 0x8888:
            hv = _flush_value(hero + board + deck[:nb], t)
        else:
            hv = NF[t >> 16]
        ties = 0
        k = nb
        for _ in range(n_opp):
            a, b = deck[k], deck[k + 1]
            k += 2
            t = bt + CV[a] + CV[b]
            if (t + 0x3333) & 0x8888:
                ov = _flush_value(board + deck[:nb] + [a, b], t)
            else:
                ov = NF[t >> 16]
            if ov > hv:
                break
            if ov == hv:
                ties += 1
        else:
            total += 1.0 / (ties + 1)
        n += 1
    return (total / n if n else 0.5), n


def _mc_ranged(hero, board, opp, iters, deadline, rnd):
    CV, NF = _CV, _NF
    dead = set(hero) | set(board)
    deck = [c for c in range(52) if c not in dead]
    L = len(deck)
    used = [False] * 52
    nb = 5 - len(board)
    ranged = [cl for cl in opp if cl is not None]
    n_rand = len(opp) - len(ranged)
    need = nb + 2 * n_rand
    bt0 = 0
    for c in board:
        bt0 += CV[c]
    ht = CV[hero[0]] + CV[hero[1]]
    total = 0.0
    n = 0
    for it in range(iters):
        if deadline is not None and it and not (it & 63) and perf_counter() > deadline:
            break
        hands = []
        ok = True
        for cl in ranged:
            m = len(cl)
            for _ in range(32):
                a, b = cl[int(rnd() * m)]
                if not used[a] and not used[b]:
                    break
            else:
                ok = False
                break
            used[a] = used[b] = True
            hands.append(a)
            hands.append(b)
        if ok:
            drawn = []
            i = 0
            while len(drawn) < need:
                j = i + int(rnd() * (L - i))
                deck[i], deck[j] = deck[j], deck[i]
                c = deck[i]
                if not used[c]:
                    drawn.append(c)
                i += 1
            hands.extend(drawn[nb:])
        for c in hands:
            used[c] = False
        if not ok:
            continue
        bt = bt0
        for i in range(nb):
            bt += CV[drawn[i]]
        t = bt + ht
        if (t + 0x3333) & 0x8888:
            hv = _flush_value(hero + board + drawn[:nb], t)
        else:
            hv = NF[t >> 16]
        ties = 0
        for k in range(0, len(hands), 2):
            a, b = hands[k], hands[k + 1]
            t = bt + CV[a] + CV[b]
            if (t + 0x3333) & 0x8888:
                ov = _flush_value(board + drawn[:nb] + [a, b], t)
            else:
                ov = NF[t >> 16]
            if ov > hv:
                break
            if ov == hv:
                ties += 1
        else:
            total += 1.0 / (ties + 1)
        n += 1
    return (total / n if n else 0.5), n


def _depth_lookup(tbl, hole, stack_bb):
    d = int(round(stack_bb * 2))
    d = max(min(tbl), min(max(tbl), d))
    return bool(tbl[d] >> hand_class(hole[0], hole[1]) & 1)


def push_ok(hole, stack_bb):
    """HU Nash: shove first-in from the SB with `stack_bb` effective (1-20)."""
    return _depth_lookup(PUSH_TABLE, hole, stack_bb)


def call_ok(hole, stack_bb):
    """HU Nash: call the SB's shove of `stack_bb` effective from the BB."""
    return _depth_lookup(CALL_TABLE, hole, stack_bb)


def _depth_frac(tbl, stack_bb):
    d = int(round(stack_bb * 2))
    bits = tbl[max(min(tbl), min(max(tbl), d))]
    return sum(CLASS_NCOMBOS[c] for c in range(169) if bits >> c & 1) / 1326.0


def nash_push_frac(stack_bb):
    """Share of hands the HU Nash SB shoves at this depth (capped 1-20 bb)."""
    return _depth_frac(PUSH_TABLE, stack_bb)


def nash_call_frac(stack_bb):
    """Share of hands the HU Nash BB calls a shove with at this depth."""
    return _depth_frac(CALL_TABLE, stack_bb)


