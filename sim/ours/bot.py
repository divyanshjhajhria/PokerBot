"""Competition No-Limit Hold'em bot -- single file, Python stdlib only (3.8+).

Sections
  1. CONFIG              rule-dependent knobs (fill from the official rules)
  2. Cards + evaluator   5/6/7-card evaluator, tables built at import
  3. Tables              generated by precompute.py into tables_data.py,
                         loaded by Bot.__init__ and carried in the pickle
  4. Equity              preflop lookups, HU matrix vs ranges, Monte Carlo
  5. Safety shell        legal-action model, validator, time/exception guard
  6. Opponent profiles   Beta-smoothed per-opponent stats, labels, ranges
  7. Bot                 entry point (strategy is a placeholder until Steps 4-7)

Normalized interface (an engine adapter maps the official API onto this):
  state = {
    'hole': ['As', 'Kd'] or [int, int],  # ints are rank*4 + suit
    'board': [...],
    'pot': int,            # all chips in the middle, incl. current-street bets
    'to_call': int,        # chips we must add to call
    'stack': int,          # our chips behind (not yet committed)
    'my_bet': int,         # our chips committed on this street      (opt, 0)
    'min_raise_to': int,   # min legal raise-to total for the street (opt)
    'max_raise_to': int,   # max raise-to total (= my_bet + stack)   (opt)
    'can_raise': bool,     # False when raising is not reopened      (opt)
    'big_blind': int,
    'num_opponents': int,  # opponents still in the hand             (opt)
  }
  action = {'action': 'fold'|'check'|'call'|'raise', 'amount': raise_to_total}
"""

