class Bot(object):
    def __init__(self, seed=0, config=None, tables=None):
        self.cfg = dict(CONFIG)
        if config:
            self.cfg.update(config)
        self.seed = seed
        self.rng = random.Random(seed)
        self.stats = {'decisions': 0, 'errors': 0, 'timeouts': 0,
                      'last_error': None, 'max_time': 0.0}
        self.profiles = {}   # team name -> Profile (reset per match/rotation)
        # Data lives on the instance so the pickle carries it (rules: no disk
        # access at play time).
        self.tables = tables if tables is not None else load_tables()
        install_tables(self.tables)

    def _ensure_tables(self):
        # After unpickling in a fresh process the module globals are empty;
        # re-point them at this instance's tables (an O(1) identity check).
        if HU_E is not self.tables['hu_e']:
            install_tables(self.tables)

    def new_match(self, seed=None):
        if seed is not None:
            self.seed = seed
        self.rng = random.Random(self.seed)
        self.profiles = {}

    def observe(self, name, ev):
        self.profile(name).observe(ev)

    def profile(self, name):
        p = self.profiles.get(name)
        if p is None:
            p = self.profiles[name] = Profile()
        return p

    # -- entry point -------------------------------------------------------
    def act(self, state):
        t0 = perf_counter()
        limit = self.cfg['time_limit']
        try:
            legal = Legal.from_state(state)
        except Exception as e:
            self._note_error(e)
            return emergency_action(state)
        action = fallback_action(legal)
        try:
            self._ensure_tables()
            proposed = self._decide(state, legal, t0 + self.cfg['mc_time_frac'] * limit)
            if perf_counter() - t0 > self.cfg['guard_time_frac'] * limit:
                self.stats['timeouts'] += 1
            else:
                action = proposed
        except Exception as e:
            self._note_error(e)
        out = to_output(sanitize(action, legal))
        dt = perf_counter() - t0
        self.stats['decisions'] += 1
        if dt > self.stats['max_time']:
            self.stats['max_time'] = dt
        return out

    def _note_error(self, e):
        self.stats['errors'] += 1
        self.stats['last_error'] = repr(e)[:300]

    # -- strategy (placeholder; replaced in Steps 3-7) -----------------------
    def _decide(self, state, L, deadline):
        hole = parse_cards(state['hole'])
        board = parse_cards(state.get('board'))
        n_opp = max(1, int(state.get('num_opponents', 1) or 1))
        pot = max(0, int(state.get('pot', 0) or 0))
        bb = L.bb
        if not board:
            eq = preflop_equity(hole, n_opp)
        else:
            iters = self.cfg['mc_iters'].get(n_opp, self.cfg['mc_iters_default'])
            eq, _ = equity_mc(hole, board, n_opp, iters=iters,
                              deadline=deadline, rng=self.rng)
        if L.to_call == 0:
            if eq > 0.62 / (n_opp ** 0.5) + 0.1:
                size = 2.5 * bb + L.my_bet if not board else L.my_bet + 0.66 * pot
                return (RAISE, size)
            return (CHECK, 0)
        need = L.to_call / float(pot + L.to_call)
        if eq > need + 0.25 and L.can_raise:
            return (RAISE, L.my_bet + L.to_call + max(pot + L.to_call, L.min_raise_to))
        if eq > need + 0.04:
            return (CALL, L.to_call)
        return (FOLD, 0)


_DEFAULT_BOT = None


def decide(state):
    """Module-level convenience entry point."""
    global _DEFAULT_BOT
    if _DEFAULT_BOT is None:
        _DEFAULT_BOT = Bot()
    return _DEFAULT_BOT.act(state)
