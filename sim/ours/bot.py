RANKS = '23456789TJQKA'
SUITS = 'cdhs'
_SUIT_ALIASES = {'♣': 'c', '♦': 'd', '♥': 'h', '♠': 's'}

HIGH, PAIR, TWO_PAIR, TRIPS, STRAIGHT, FLUSH, FULL_HOUSE, QUADS, STRAIGHT_FLUSH = range(9)
CATEGORY_NAMES = ('high', 'pair', 'two_pair', 'trips', 'straight', 'flush',
                  'full_house', 'quads', 'straight_flush')


def parse_card(x):
    """'As' / 'aS' / '10h' / 'T♥' / int -> int in [0, 52)."""
    if isinstance(x, int):
        if 0 <= x < 52:
            return x
        raise ValueError('card int out of range: %r' % (x,))
    s = str(x).strip()
    if len(s) == 3 and s[:2] == '10':
        s = 'T' + s[2]
    if len(s) != 2:
        raise ValueError('bad card: %r' % (x,))
    r = RANKS.index(s[0].upper())
    su = s[1].lower()
    su = _SUIT_ALIASES.get(s[1], su)
    return r * 4 + SUITS.index(su)


def parse_cards(xs):
    return [parse_card(x) for x in (xs or [])]


def card_str(c):
    return RANKS[c >> 2] + SUITS[c & 3]


# Per-card additive code: rank multiset in base 5 above bit 16, suit counts in
# four nibbles below.  Summing any <=7 cards never carries between fields.
_CV = [((5 ** (c >> 2)) << 16) | (1 << (4 * (c & 3))) for c in range(52)]
_POW5 = [5 ** r for r in range(13)]


def _kick(cat, ranks):
    v = cat << 20
    sh = 16
    for r in ranks:
        v |= r << sh
        sh -= 4
    return v


def _build_straight_table():
    t = [-1] * 8192
    for m in range(8192):
        for hi in range(12, 3, -1):
            w = 0x1F << (hi - 4)
            if m & w == w:
                t[m] = hi
                break
        else:
            if m & 0x100F == 0x100F:  # A-2-3-4-5
                t[m] = 3
    return t


_STRAIGHT_HI = _build_straight_table()


def _nonflush_value(cnt):
    quads, trips, pairs, present = [], [], [], []
    mask = 0
    for r in range(12, -1, -1):
        n = cnt[r]
        if not n:
            continue
        mask |= 1 << r
        present.append(r)
        if n == 4:
            quads.append(r)
        elif n == 3:
            trips.append(r)
        elif n == 2:
            pairs.append(r)
    if quads:
        q = quads[0]
        return _kick(QUADS, [q, next(r for r in present if r != q)])
    if trips and (len(trips) > 1 or pairs):
        t = trips[0]
        return _kick(FULL_HOUSE, [t, max(trips[1:] + pairs)])
    sh = _STRAIGHT_HI[mask]
    if sh >= 0:
        return _kick(STRAIGHT, [sh])
    if trips:
        t = trips[0]
        return _kick(TRIPS, [t] + [r for r in present if r != t][:2])
    if len(pairs) > 1:
        p1, p2 = pairs[0], pairs[1]
        return _kick(TWO_PAIR, [p1, p2, next(r for r in present if r != p1 and r != p2)])
    if pairs:
        p = pairs[0]
        return _kick(PAIR, [p] + [r for r in present if r != p][:3])
    return _kick(HIGH, present[:5])


def _build_eval_tables():
    fl = [0] * 8192
    for m in range(8192):
        if bin(m).count('1') < 5:
            continue
        sh = _STRAIGHT_HI[m]
        if sh >= 0:
            fl[m] = _kick(STRAIGHT_FLUSH, [sh])
        else:
            fl[m] = _kick(FLUSH, [r for r in range(12, -1, -1) if m >> r & 1][:5])
    nf = {}
    pw = _POW5
    for k in (5, 6, 7):
        for combo in combinations_with_replacement(range(13), k):
            cnt = [0] * 13
            for r in combo:
                cnt[r] += 1
            if max(cnt) > 4:
                continue
            key = 0
            for r in combo:
                key += pw[r]
            nf[key] = _nonflush_value(cnt)
    return fl, nf


_FL, _NF = _build_eval_tables()


def evaluate(cards):
    """Best hand value of 5, 6 or 7 int cards. Higher is better."""
    t = 0
    for c in cards:
        t += _CV[c]
    f = (t + 0x3333) & 0x8888
    if f:  # some suit has >= 5 cards; with <= 7 cards no FH/quads possible
        s = (f.bit_length() - 4) >> 2
        m = 0
        for c in cards:
            if c & 3 == s:
                m |= 1 << (c >> 2)
        return _FL[m]
    return _NF[t >> 16]


def _flush_value(cards, t):
    s = (((t + 0x3333) & 0x8888).bit_length() - 4) >> 2
    m = 0
    for c in cards:
        if c & 3 == s:
            m |= 1 << (c >> 2)
    return _FL[m]


def hand_category(value):
    return value >> 20


# Starting-hand classes: 169 cells of a 13x13 grid.
def hand_class(c1, c2):
    r1, r2 = c1 >> 2, c2 >> 2
    if r1 < r2:
        r1, r2 = r2, r1
    if r1 == r2:
        return r1 * 13 + r1
    if (c1 & 3) == (c2 & 3):
        return r1 * 13 + r2      # suited: row = high rank
    return r2 * 13 + r1          # offsuit: row = low rank


def _class_name(i):
    a, b = divmod(i, 13)
    if a == b:
        return RANKS[a] * 2
    if a > b:
        return RANKS[a] + RANKS[b] + 's'
    return RANKS[b] + RANKS[a] + 'o'


CLASS_NAMES = [_class_name(i) for i in range(169)]
CLASS_INDEX = dict((n, i) for i, n in enumerate(CLASS_NAMES))
CLASS_COMBOS = [[] for _ in range(169)]
for _a in range(52):
    for _b in range(_a + 1, 52):
        CLASS_COMBOS[hand_class(_a, _b)].append((_a, _b))
CLASS_NCOMBOS = [len(x) for x in CLASS_COMBOS]

