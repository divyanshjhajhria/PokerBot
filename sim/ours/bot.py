FOLD, CHECK, CALL, RAISE = 'fold', 'check', 'call', 'raise'


class Legal(object):
    """What we may do right now, derived defensively from the state."""
    __slots__ = ('to_call', 'stack', 'my_bet', 'can_check', 'can_raise',
                 'min_raise_to', 'max_raise_to', 'bb')

    def __init__(self, to_call, stack, my_bet=0, min_raise_to=None,
                 max_raise_to=None, can_raise=None, bb=1, can_check=None):
        self.to_call = max(0, int(to_call))
        self.stack = max(0, int(stack))
        self.my_bet = max(0, int(my_bet))
        self.bb = max(1, int(bb))
        self.can_check = (self.to_call == 0) if can_check is None else bool(can_check)
        cap = self.my_bet + self.stack
        self.max_raise_to = cap if max_raise_to is None else min(int(max_raise_to), cap)
        if min_raise_to is None:
            inc = max(self.bb, self.to_call)
            min_raise_to = self.my_bet + self.to_call + inc
        self.min_raise_to = int(min_raise_to)
        call_to = self.my_bet + self.to_call
        raisable = self.max_raise_to > call_to
        self.can_raise = raisable if can_raise is None else (bool(can_raise) and raisable)

    @classmethod
    def from_state(cls, s):
        return cls(to_call=s.get('to_call', 0) or 0,
                   stack=s['stack'],
                   my_bet=s.get('my_bet', 0) or 0,
                   min_raise_to=s.get('min_raise_to'),
                   max_raise_to=s.get('max_raise_to'),
                   can_raise=s.get('can_raise'),
                   bb=s.get('big_blind', 1) or 1,
                   can_check=s.get('can_check'))


def fallback_action(legal):
    return (CHECK, 0) if legal.can_check else (FOLD, 0)


def sanitize(action, legal, snap_bb=None):
    """Map any proposed action onto a legal one. Never raises."""
    try:
        return _sanitize(action, legal, snap_bb)
    except Exception:
        return fallback_action(legal)


def _sanitize(action, L, snap_bb):
    if isinstance(action, dict):
        kind, amt = action.get('action'), action.get('amount', 0)
    elif isinstance(action, (tuple, list)):
        kind = action[0]
        amt = action[1] if len(action) > 1 else 0
    else:
        kind, amt = action, 0
    kind = str(kind).lower()

    if kind in (FOLD, CHECK):
        return fallback_action(L)
    if kind == CALL:
        if L.to_call <= 0:
            return fallback_action(L)
        if L.stack <= 0:
            return fallback_action(L)
        return (CALL, min(L.to_call, L.stack))
    if kind in (RAISE, 'bet', 'allin', 'all_in', 'all-in', 'shove', 'jam'):
        if kind not in (RAISE, 'bet'):
            amt = L.max_raise_to
        if not L.can_raise:
            return (CALL, min(L.to_call, L.stack)) if L.to_call > 0 else fallback_action(L)
        amt = float(amt)
        if amt != amt:  # NaN
            return fallback_action(L)
        amt = max(int(round(amt)), L.min_raise_to)
        if amt >= L.max_raise_to:
            amt = L.max_raise_to          # all-in, possibly short of a full raise
        if amt < L.min_raise_to and not CONFIG['allin_for_less_ok']:
            return (CALL, min(L.to_call, L.stack)) if L.to_call > 0 else fallback_action(L)
        snap = CONFIG['snap_allin_bb'] if snap_bb is None else snap_bb
        if L.max_raise_to - amt < snap * L.bb:
            amt = L.max_raise_to
        return (RAISE, amt)
    return fallback_action(L)


def to_output(action):
    kind, amt = action
    return {'action': kind, 'amount': int(amt)}


def emergency_action(state):
    try:
        if not (state.get('to_call') or 0):
            return {'action': CHECK, 'amount': 0}
    except Exception:
        pass
    return {'action': FOLD, 'amount': 0}


