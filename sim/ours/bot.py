PREFLOP_EQ = None   # {n_opp: [169]} equity vs n random hands (heads-up: n=1)
HU_E = None         # flat 169*169: equity of class i vs class j (card removal)
HU_W = None         # flat 169*169: number of non-conflicting combo pairs
PUSH_TABLE = None   # {2*bb: 169-bit int} SB first-in shove set (HU Nash)
CALL_TABLE = None   # {2*bb: 169-bit int} BB call set vs that shove
HAND_ORDER = list(range(169))   # classes, strongest first (HU vs random)


def load_tables():
    """Read the generated tables module into a plain, picklable dict."""
    import tables_data as td
    raw = bytes.fromhex(td.HU_EQ_HEX)
    return {
        'meta': dict(td.META),
        'preflop_eq': dict((int(n), list(v)) for n, v in td.PREFLOP_EQ.items()),
        'hu_e': [(raw[2 * k] << 8 | raw[2 * k + 1]) / 65535.0 for k in range(169 * 169)],
        'hu_w': list(bytes.fromhex(td.HU_W_HEX)),
        'push': dict((int(d), int(h, 16)) for d, h in td.PUSH_HEX.items()),
        'call': dict((int(d), int(h, 16)) for d, h in td.CALL_HEX.items()),
    }


def install_tables(t):
    global PREFLOP_EQ, HU_E, HU_W, PUSH_TABLE, CALL_TABLE, HAND_ORDER
    PREFLOP_EQ, HU_E, HU_W = t['preflop_eq'], t['hu_e'], t['hu_w']
    PUSH_TABLE, CALL_TABLE = t['push'], t['call']
    eq1 = PREFLOP_EQ[1]
    HAND_ORDER = sorted(range(169), key=lambda i: -eq1[i])


